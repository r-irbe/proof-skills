#!/usr/bin/env python3
"""Automated blueprint section generator for EASCI modules.

Strict 7-bit ASCII only (INV-001).
Complies with tools/blueprint_tex_guard.py and docs/easci/lean/blueprint/probe.py.
"""

import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LEAN_ROOT = ROOT / "docs" / "easci" / "lean"
BLUEPRINT_SRC = LEAN_ROOT / "blueprint" / "src"
SECTIONS_DIR = BLUEPRINT_SRC / "sections"
CONTENT_TEX = BLUEPRINT_SRC / "content.tex"

def sanitize_tex(text: str) -> str:
    """Ensure strict ASCII, no html entities, no double backslashes before letters."""
    # Ensure 7-bit ASCII (INV-001)
    text = text.encode("ascii", "ignore").decode("ascii")
    # Entity replacements
    text = text.replace("&nbsp;", " ").replace("&amp;", "\\&")
    text = text.replace("&lt;", "<").replace("&gt;", ">")
    text = text.replace("&le;", "\\le").replace("&ge;", "\\ge")
    text = text.replace("&times;", "\\times").replace("&minus;", "-")
    text = text.replace("&rarr;", "->").replace("&larr;", "<-")
    text = re.sub(r"&#\d+;", " ", text)
    # Remove doubled backslash before letters (LaTeX command corruption)
    text = re.sub(r"\\\\(?=[A-Za-z])", "\\\\", text)
    # Escape unescaped hashes and percents
    text = re.sub(r"(?<!\\)#", "\\#", text)
    text = re.sub(r"(?<!\\)%", "\\%", text)
    # Sanitize backticks
    text = re.sub(r"`([^`]+)`", r"\\texttt{\1}", text)
    return text

def extract_module_info(lean_path: Path):
    content = lean_path.read_text(encoding="utf-8", errors="replace")
    
    # Extract namespace
    ns_match = re.search(r"^namespace\s+([A-Za-z0-9_\.]+)", content, re.M)
    namespace = ns_match.group(1) if ns_match else "EASCI"
    
    # Extract module docstring
    doc_match = re.search(r"/-\*!(.*?)-/\n", content, re.S)
    module_doc = doc_match.group(1).strip() if doc_match else f"Module {lean_path.name}"
    # take first 3 lines of module doc
    doc_lines = [l.strip("#* \t") for l in module_doc.splitlines() if l.strip("#* \t")]
    synopsis = " ".join(doc_lines[:2]) if doc_lines else lean_path.stem
    synopsis = sanitize_tex(synopsis)

    # Extract declarations with preceding docstrings
    # pattern for decls:
    decl_pattern = re.compile(
        r"(?:/--(?P<doc>.*?)-/\s*)?"
        r"^(?:noncomputable\s+)?(?P<kind>theorem|lemma|def|abbrev|instance|structure)\s+"
        r"(?P<name>[A-Za-z0-9_\'\.]+)\b",
        re.M | re.S
    )

    decls = []
    for m in decl_pattern.finditer(content):
        kind = m.group("kind")
        name = m.group("name")
        doc = m.group("doc")
        doc_str = doc.strip().replace("\n", " ") if doc else ""
        doc_str = sanitize_tex(doc_str)
        # ignore internal or empty names
        if not name or name.startswith("_"):
            continue
        decls.append({
            "kind": kind,
            "name": name,
            "doc": doc_str,
        })
    return namespace, synopsis, decls

def generate_section(lean_path: Path, section_slug: str, prefix: str):
    namespace, synopsis, decls = extract_module_info(lean_path)
    if not decls:
        return None, 0

    rel_lean = lean_path.relative_to(LEAN_ROOT)
    sec_title = f"{lean_path.stem}: Formal Verification and Specification"
    # Ensure title contains no math or control sequences
    sec_title = re.sub(r"[^A-Za-z0-9_:\- ]", "", sec_title)

    lines = [
        f"% Blueprint section for {rel_lean}",
        f"% Generated by tools/expand_blueprint.py",
        f"% Declarations: {len(decls)}",
        "",
        f"\\section{{{sec_title}}}\\label{{sec:{section_slug}}}",
        "",
        f"This section blueprints \\texttt{{{rel_lean}}}, formalizing {synopsis}.",
        "",
    ]

    for d in decls:
        name = d["name"]
        kind = d["kind"]
        env = "theorem" if kind in ("theorem", "lemma") else "definition"
        clean_name = re.sub(r"[^A-Za-z0-9]", "", name.replace("'", "Prime").replace(".", "_"))
        label = f"{prefix}{clean_name}"
        full_lean_name = f"{namespace}.{name}" if not name.startswith(namespace) else name

        doc = d["doc"]
        if not doc:
            doc = f"Formalized {kind} \\texttt{{{name}}} in namespace \\texttt{{{namespace}}}."
        else:
            # truncate doc to reasonable length
            if len(doc) > 300:
                doc = doc[:297] + "..."

        lines.extend([
            f"\\begin{{{env}}}\\label{{{label}}}\\lean{{{full_lean_name}}}\\leanok",
            doc,
            f"\\end{{{env}}}",
            "",
        ])

    tex_content = "\n".join(lines)
    tex_path = SECTIONS_DIR / f"{section_slug}.tex"
    tex_path.write_text(tex_content, encoding="utf-8")
    return tex_path, len(decls)

def batch_expand(target_decls: int = 750):
    content_text = CONTENT_TEX.read_text(encoding="utf-8")
    existing_inputs = set(re.findall(r"\\input\{sections/([^\}]+)\}", content_text))

    # Candidate directories across all of EASCI
    search_dirs = [
        LEAN_ROOT / "EASCI",
    ]

    candidates = []
    for sdir in search_dirs:
        if not sdir.exists():
            continue
        for lean_file in sorted(sdir.rglob("*.lean")):
            if ".scratch" in lean_file.parts:
                continue
            rel = lean_file.relative_to(LEAN_ROOT)
            slug = rel.as_posix().replace("/", "-").replace(".lean", "").lower()
            if slug in existing_inputs:
                continue
            candidates.append((lean_file, slug))

    total_added = 0
    new_slugs = []

    for lean_path, slug in candidates:
        if total_added >= target_decls:
            break
        # Create a prefix based on slug components
        parts = slug.split("-")
        prefix = "".join(p[:3].capitalize() for p in parts)
        tex_path, count = generate_section(lean_path, slug, prefix)
        if count > 0:
            total_added += count
            new_slugs.append(slug)
            print(f"Generated {slug}: +{count} decls (total added: {total_added})")

    if new_slugs:
        # Insert into content.tex right before \section{Upstream-candidate notes}
        insert_marker = "\\section{Upstream-candidate notes}"
        if insert_marker in content_text:
            insertion = "\n".join(f"\\input{{sections/{s}}}" for s in new_slugs) + "\n"
            new_content = content_text.replace(insert_marker, insertion + insert_marker)
            CONTENT_TEX.write_text(new_content, encoding="utf-8")
            print(f"Updated content.tex with {len(new_slugs)} new sections.")
        else:
            print("Warning: insert marker not found in content.tex")

    print(f"Batch expansion complete: added {total_added} declarations across {len(new_slugs)} modules.")
    return total_added

def main():
    if len(sys.argv) > 1 and sys.argv[1] == "--batch":
        target = int(sys.argv[2]) if len(sys.argv) > 2 else 750
        batch_expand(target)
        return

    if len(sys.argv) < 4:
        print("Usage: expand_blueprint.py <relative-lean-path> <section-slug> <label-prefix>")
        print("   or: expand_blueprint.py --batch [target-declarations]")
        sys.exit(1)
    lean_rel = sys.argv[1]
    slug = sys.argv[2]
    prefix = sys.argv[3]

    lean_path = LEAN_ROOT / lean_rel
    if not lean_path.exists():
        print(f"Error: {lean_path} does not exist")
        sys.exit(1)

    tex_path, count = generate_section(lean_path, slug, prefix)
    print(f"Generated {tex_path} with {count} declarations.")

if __name__ == "__main__":
    main()
