#!/usr/bin/env python3
"""Automated blueprint section generator for Lean 4 modules.

Supports single-module generation, `--batch [target-decls]`, and
`--auto-discover` (auto-discovers un-blueprinted modules from `lean-project.toml`
or `lakefile.lean`).
Strict 7-bit ASCII only (INV-001).
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
if str(_HERE) not in sys.path:
    sys.path.insert(0, str(_HERE))

try:
    from project_config import load_project_config
    _CFG = load_project_config()
    LEAN_ROOT = _CFG.root
    DEFAULT_PROJECT = _CFG.lean_dir if _CFG.lean_dir not in ("", ".") else _CFG.name
except Exception:
    ROOT = Path(__file__).resolve().parent.parent
    LEAN_ROOT = ROOT / "docs" / "easci" / "lean"
    DEFAULT_PROJECT = "EASCI"

BLUEPRINT_SRC = LEAN_ROOT / "blueprint" / "src"
SECTIONS_DIR = BLUEPRINT_SRC / "sections"
CONTENT_TEX = BLUEPRINT_SRC / "content.tex"


def sanitize_tex(text: str) -> str:
    """Ensure strict ASCII, no html entities, no double backslashes before letters."""
    text = text.encode("ascii", "ignore").decode("ascii")
    text = text.replace("&nbsp;", " ").replace("&amp;", "\\&")
    text = text.replace("&lt;", "<").replace("&gt;", ">")
    text = text.replace("&le;", "\\le").replace("&ge;", "\\ge")
    text = text.replace("&times;", "\\times").replace("&minus;", "-")
    text = text.replace("&rarr;", "->").replace("&larr;", "<-")
    text = re.sub(r"&#\d+;", " ", text)
    text = re.sub(r"\\\\(?=[A-Za-z])", "\\\\", text)
    text = re.sub(r"(?<!\\)#", "\\#", text)
    text = re.sub(r"(?<!\\)%", "\\%", text)
    text = re.sub(r"`([^`]+)`", r"\\texttt{\1}", text)
    return text


def extract_module_info(lean_path: Path, default_ns: str = DEFAULT_PROJECT):
    content = lean_path.read_text(encoding="utf-8", errors="replace")
    ns_match = re.search(r"^namespace\s+([A-Za-z0-9_\.]+)", content, re.M)
    namespace = ns_match.group(1) if ns_match else default_ns

    doc_match = re.search(r"/-\*!(.*?)-/\n", content, re.S)
    module_doc = doc_match.group(1).strip() if doc_match else f"Module {lean_path.name}"
    doc_lines = [l.strip("#* \t") for l in module_doc.splitlines() if l.strip("#* \t")]
    synopsis = " ".join(doc_lines[:2]) if doc_lines else lean_path.stem
    synopsis = sanitize_tex(synopsis)

    decl_pattern = re.compile(
        r"(?:/--(?P<doc>.*?)-/\s*)?"
        r"^(?:noncomputable\s+)?(?P<kind>theorem|lemma|def|abbrev|instance|structure)\s+"
        r"(?P<name>[A-Za-z0-9_\'\.]+)\b",
        re.M | re.S,
    )

    decls = []
    for m in decl_pattern.finditer(content):
        kind = m.group("kind")
        name = m.group("name")
        doc = m.group("doc")
        doc_str = doc.strip().replace("\n", " ") if doc else ""
        doc_str = sanitize_tex(doc_str)
        if not name or name.startswith("_"):
            continue
        decls.append({"kind": kind, "name": name, "doc": doc_str})
    return namespace, synopsis, decls


def generate_section(
    lean_path: Path,
    section_slug: str,
    prefix: str,
    lean_root: Path | None = None,
    sections_dir: Path | None = None,
):
    lroot = lean_root or LEAN_ROOT
    sdir = sections_dir or SECTIONS_DIR
    namespace, synopsis, decls = extract_module_info(lean_path)
    if not decls:
        return None, 0

    try:
        rel_lean = lean_path.relative_to(lroot)
    except ValueError:
        rel_lean = Path(lean_path.name)
    sec_title = f"{lean_path.stem}: Formal Verification and Specification"
    sec_title = re.sub(r"[^A-Za-z0-9_:\- ]", "", sec_title)

    lines = [
        f"% Blueprint section for {rel_lean}",
        f"% Generated by expand_blueprint.py",
        f"% Declarations: {len(decls)}",
        "",
        f"\\section{{{sec_title}}}\\label{{sec:{section_slug}}}",
        "",
        f"This section blueprints \\texttt{{{rel_lean}}}, formalizing {synopsis}.",
        "",
    ]

    for d in decls:
        name = d["name"]
        kind = d["kind"]
        env = "theorem" if kind in ("theorem", "lemma") else "definition"
        clean_name = re.sub(r"[^A-Za-z0-9]", "", name.replace("'", "Prime").replace(".", "_"))
        label = f"{prefix}{clean_name}"
        full_lean_name = f"{namespace}.{name}" if not name.startswith(namespace) else name

        doc = d["doc"]
        if not doc:
            doc = f"Formalized {kind} \\texttt{{{name}}} in namespace \\texttt{{{namespace}}}."
        elif len(doc) > 300:
            doc = doc[:297] + "..."

        lines.extend([
            f"\\begin{{{env}}}\\label{{{label}}}\\lean{{{full_lean_name}}}\\leanok",
            doc,
            f"\\end{{{env}}}",
            "",
        ])

    tex_content = "\n".join(lines)
    sdir.mkdir(parents=True, exist_ok=True)
    tex_path = sdir / f"{section_slug}.tex"
    tex_path.write_text(tex_content, encoding="utf-8")
    return tex_path, len(decls)


def batch_expand(
    target_decls: int = 750,
    lean_root: Path | None = None,
    lean_dir: str | None = None,
    dry_run: bool = False,
) -> int:
    lroot = lean_root or LEAN_ROOT
    ldir = lean_dir or DEFAULT_PROJECT
    bsrc = lroot / "blueprint" / "src"
    ctex = bsrc / "content.tex"
    sdir = bsrc / "sections"

    content_text = ctex.read_text(encoding="utf-8") if ctex.exists() else ""
    existing_inputs = set(re.findall(r"\\input\{sections/([^\}]+)\}", content_text))

    search_dir = lroot if ldir in ("", ".") else (lroot / ldir)
    candidates = []
    if search_dir.exists():
        for lean_file in sorted(search_dir.rglob("*.lean")):
            if ".scratch" in lean_file.parts or ".lake" in lean_file.parts:
                continue
            rel = lean_file.relative_to(lroot)
            slug = rel.as_posix().replace("/", "-").replace(".lean", "").lower()
            if slug in existing_inputs:
                continue
            candidates.append((lean_file, slug))

    if dry_run:
        print(f"Auto-discovered {len(candidates)} un-blueprinted module(s) under {search_dir}.")
        for lf, sl in candidates[:20]:
            print(f"  - {lf.relative_to(lroot)} -> {sl}.tex")
        return len(candidates)

    total_added = 0
    new_slugs = []

    for lean_path, slug in candidates:
        if total_added >= target_decls:
            break
        parts = slug.split("-")
        prefix = "".join(p[:3].capitalize() for p in parts)
        _, count = generate_section(lean_path, slug, prefix, lean_root=lroot, sections_dir=sdir)
        if count > 0:
            total_added += count
            new_slugs.append(slug)
            print(f"Generated {slug}: +{count} decls (total added: {total_added})")

    if new_slugs and ctex.exists():
        insert_marker = "\\section{Upstream-candidate notes}"
        if insert_marker in content_text:
            insertion = "\n".join(f"\\input{{sections/{s}}}" for s in new_slugs) + "\n"
            new_content = content_text.replace(insert_marker, insertion + insert_marker)
            ctex.write_text(new_content, encoding="utf-8")
            print(f"Updated content.tex with {len(new_slugs)} new sections.")
        else:
            print("Warning: insert marker not found in content.tex")

    print(f"Batch expansion complete: added {total_added} declarations across {len(new_slugs)} modules.")
    return total_added


def main(argv: list[str] | None = None) -> int:
    args_list = list(sys.argv[1:] if argv is None else argv)
    if args_list and args_list[0] in ("--batch", "--auto-discover"):
        ap = argparse.ArgumentParser(description=__doc__)
        ap.add_argument("--batch", nargs="?", const=750, type=int, help="Target declaration count")
        ap.add_argument("--auto-discover", action="store_true", help="Auto-discover un-blueprinted modules")
        ap.add_argument("--limit", type=int, default=750, help="Max declarations to add")
        ap.add_argument("--root", type=Path, default=None, help="Lean project root")
        ap.add_argument("--lean-dir", type=str, default=None, help="Lean corpus subdir")
        ap.add_argument("--dry-run", action="store_true", help="Only list discovered modules")
        ns = ap.parse_args(args_list)
        target = ns.batch if ns.batch is not None else ns.limit
        lroot = ns.root.resolve() if ns.root else LEAN_ROOT
        batch_expand(target_decls=target, lean_root=lroot, lean_dir=ns.lean_dir, dry_run=ns.dry_run)
        return 0

    if len(args_list) < 3:
        print("Usage: expand_blueprint.py <relative-lean-path> <section-slug> <label-prefix>")
        print("   or: expand_blueprint.py --batch [target-declarations]")
        print("   or: expand_blueprint.py --auto-discover [--dry-run] [--limit N]")
        return 1

    lean_rel, slug, prefix = args_list[0], args_list[1], args_list[2]
    lean_path = LEAN_ROOT / lean_rel
    if not lean_path.exists():
        print(f"Error: {lean_path} does not exist")
        return 1

    tex_path, count = generate_section(lean_path, slug, prefix)
    print(f"Generated {tex_path} with {count} declarations.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
