#!/usr/bin/env python3
"""
build_timing_report.py - render a lake-timer JSON into a
committed Markdown baseline at `docs/tracking/lake_timing.md`.

Inputs
------
  $1  Path to a `<slice>-build-timing.json` produced by
      `scripts/lean/lake_timer.sh N`.  The JSON is a `{target: seconds}`
      mapping.
  $2  Output Markdown path (defaults to `docs/tracking/lake_timing.md`).
  --slow-sec N          Highlight threshold in seconds (default 120).
  --top N               How many slowest targets to list (default 25).
  --slice N             Slice identifier to record in the report (default 0).
  --project-prefix P    Root module namespace prefix for bucketing (auto-detected if omitted).

Output
------
A Markdown report with:
  * Header (slice ID, timestamp, total targets, sum-of-seconds,
    wall-clock-equivalent if known).
  * Top-N slowest targets table.
  * Slow-threshold (> N s) targets table.
  * Per-bucket aggregate (<Project>.Foundations, <Project>.StochasticCCV, ...).

This script is read-only with respect to the lake build cache; it only
parses the JSON emitted by `lake_timer.sh`.

Wired into `scripts/lean/enforce_all.sh` as Phase 7 (Build Timing).
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path


def _bucket_for(target: str, project_prefix: str = "") -> str:
    """Coarse-grained bucket: the second component of the dotted module path."""
    parts = target.split(".")
    if len(parts) >= 2 and (not project_prefix or parts[0] == project_prefix):
        return f"{parts[0]}.{parts[1]}"
    if parts:
        return parts[0]
    return "(other)"


def render(
    timings: dict[str, float],
    slice_id: str,
    slow_sec: float,
    top_n: int,
    project_prefix: str = "",
) -> str:
    lines: list[str] = []
    now = dt.datetime.now(dt.UTC).strftime("%Y-%m-%d %H:%M UTC")

    total_targets = len(timings)
    total_sec = sum(timings.values())
    slow = [(t, s) for t, s in timings.items() if s > slow_sec]
    slow.sort(key=lambda x: -x[1])
    ordered = sorted(timings.items(), key=lambda x: -x[1])

    lines.append("# Lake Build Timing Baseline")
    lines.append("")
    lines.append(f"_Generated by `build_timing_report.py` at {now}._")
    lines.append("")
    lines.append("Captures per-target wall-clock timings from the most recent ")
    lines.append("`lake build --verbose` invocation, as parsed by ")
    lines.append("`lake_timer.sh`. Re-generate via:")
    lines.append("")
    lines.append("```bash")
    lines.append("lake clean")
    lines.append("LAKE_TIMER_OUTDIR=/tmp/lake-timing-baseline \\")
    lines.append("  bash scripts/lean/lake_timer.sh 0")
    lines.append("python3 scripts/lean/build_timing_report.py \\")
    lines.append("  /tmp/lake-timing-baseline/slice-0-build-timing.json")
    lines.append("```")
    lines.append("")
    lines.append("Or simply run `bash scripts/lean/enforce_all.sh` (Phase 7 invokes ")
    lines.append("this script automatically when the JSON is fresh).")
    lines.append("")

    lines.append("## Summary")
    lines.append("")
    lines.append("| Metric | Value |")
    lines.append("|---|---:|")
    lines.append(f"| Slice ID | `{slice_id}` |")
    lines.append(f"| Timed targets | {total_targets} |")
    lines.append(f"| Sum of per-target seconds | {total_sec:,.1f} s |")
    lines.append("| Wall-clock equivalent (~= sum / cpu count) | see job parallelism |")
    lines.append(f"| Slow-target threshold | {slow_sec:.0f} s |")
    lines.append(f"| Slow targets (`> threshold`) | {len(slow)} |")
    lines.append("")

    if not ordered:
        lines.append("> No `Built X (Y)` lines found in the source log. The ")
        lines.append("> build was likely a cache replay. Run `lake clean` first ")
        lines.append("> to force re-elaboration and capture wall-clock timings.")
        lines.append("")
        return "\n".join(lines) + "\n"

    lines.append(f"## Top {top_n} slowest targets")
    lines.append("")
    lines.append("| Rank | Target | Seconds |")
    lines.append("|---:|---|---:|")
    for i, (target, sec) in enumerate(ordered[:top_n], start=1):
        lines.append(f"| {i} | `{target}` | {sec:,.2f} |")
    lines.append("")

    if slow:
        lines.append(f"## Targets exceeding {slow_sec:.0f} s ({len(slow)})")
        lines.append("")
        lines.append("| Target | Seconds | Over budget |")
        lines.append("|---|---:|---:|")
        for target, sec in slow:
            lines.append(f"| `{target}` | {sec:,.2f} | +{sec - slow_sec:,.2f} |")
        lines.append("")
    else:
        lines.append(f"## Targets exceeding {slow_sec:.0f} s")
        lines.append("")
        lines.append("None.")
        lines.append("")

    buckets: dict[str, float] = {}
    counts: dict[str, int] = {}
    for target, sec in timings.items():
        b = _bucket_for(target, project_prefix)
        buckets[b] = buckets.get(b, 0.0) + sec
        counts[b] = counts.get(b, 0) + 1
    lines.append("## Aggregate by bucket")
    lines.append("")
    lines.append("| Bucket | Targets | Seconds | Avg s/target |")
    lines.append("|---|---:|---:|---:|")
    for bucket, sec in sorted(buckets.items(), key=lambda x: -x[1]):
        n = counts[bucket]
        avg = sec / n if n else 0.0
        lines.append(f"| `{bucket}` | {n} | {sec:,.1f} | {avg:,.2f} |")
    lines.append("")

    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("json_path", type=Path)
    p.add_argument(
        "output_path",
        type=Path,
        nargs="?",
        default=Path("docs/tracking/lake_timing.md"),
    )
    p.add_argument("--slow-sec", type=float, default=120.0)
    p.add_argument("--top", type=int, default=25, dest="top_n")
    p.add_argument("--slice", default="0", dest="slice_id")
    p.add_argument("--project-prefix", default="", dest="project_prefix")
    args = p.parse_args(argv)

    if not args.json_path.is_file():
        print(f"error: {args.json_path} does not exist", file=sys.stderr)
        return 2

    try:
        timings = json.loads(args.json_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        print(f"error: {args.json_path} is not valid JSON: {exc}", file=sys.stderr)
        return 2

    if not isinstance(timings, dict):
        print("error: expected a JSON object mapping target -> seconds", file=sys.stderr)
        return 2

    parsed: dict[str, float] = {}
    for k, v in timings.items():
        try:
            parsed[str(k)] = float(v)
        except (TypeError, ValueError):
            continue

    markdown = render(parsed, args.slice_id, args.slow_sec, args.top_n, args.project_prefix)
    args.output_path.parent.mkdir(parents=True, exist_ok=True)
    args.output_path.write_text(markdown, encoding="utf-8")
    print(f"wrote {args.output_path} ({len(parsed)} targets)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
