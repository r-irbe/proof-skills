"""Report renderer v1 - turns extraction candidates into the
human-facing elegance report (design note C4: non-judgmental,
teaching posture - the report OFFERS alternatives, it never demands
adoption).

Output shape (per file, Markdown):

    ## <file>
    ### block at lines A-B
    Current proof:
    ```lean
    <tactic text>
    ```
    An alternative worth knowing:
    - Since `x * x` appears 4 times, it could be named once
      (route: extraction-general; saves ~N lines; cost 0.40 -> -4.80).

The verbose-sketch phrasing follows the Lean-STaR thoughts-before-
steps precedent (LeanDojo dossier) and the verbose-lean4 discourse
moves: one sentence per candidate, named evidence, no judgment words
("bad", "wrong", "should"); the closing line always notes the
current proof is correct.
"""

from __future__ import annotations

import sys as _sys
from pathlib import Path as _Path
if str(_Path(__file__).resolve().parent) not in _sys.path:
    _sys.path.insert(0, str(_Path(__file__).resolve().parent))

from dataclasses import dataclass, field

from cost_ranker import TwoAxisScore, cost


@dataclass
class BlockReport:
    """One proof block's report entry."""

    line_start: int
    line_end: int
    proof_text: str
    candidates: list = field(default_factory=list)
    theorem: str = ""
    two_axis_scores: list[TwoAxisScore] = field(default_factory=list)


def _sketch(candidate, before_lines: int) -> str:
    """One-sentence verbose sketch for a candidate (non-judgmental)."""
    after_lines = max(0, before_lines - candidate.estimated_lines_saved)
    before_kernel = getattr(candidate, "before_kernel_cost", 0.0)
    after_kernel = getattr(candidate, "kernel_cost", getattr(candidate, "after_kernel_cost", 0.0))
    legibility = getattr(candidate, "legibility", "standard")
    before_cost = cost(before_lines, kernel_cost=before_kernel)
    after_cost = cost(
        after_lines,
        (candidate.estimated_lines_saved and 1) or 0,
        kernel_cost=after_kernel,
    )
    score = TwoAxisScore(
        elegance_cost=after_cost,
        kernel_cost=after_kernel,
        legibility=legibility,
    )
    if hasattr(candidate, "two_axis_score"):
        candidate.two_axis_score = score
    if candidate.kind == "have-block":
        reason = (
            f"the block `{candidate.evidence}` already isolates its content; "
            f"naming it at module level makes it reusable"
        )
    else:
        reason = (
            f"`{candidate.evidence}` occurs {candidate.occurrences} times; "
            f"naming it once would shorten the proof"
        )
    return (
        f"- Since {reason} (route: {candidate.route}; "
        f"estimated saving ~{candidate.estimated_lines_saved} lines; "
        f"cost {before_cost:.2f} -> {after_cost:.2f}; "
        f"two-axis: {{elegance_cost: {score.elegance_cost:.2f}, "
        f"kernel_cost: {score.kernel_cost:.2f}, legibility: '{score.legibility}'}})."
    )


def render_block(block: BlockReport) -> str:
    lines = [
        f"#### proof at lines {block.line_start}-{block.line_end}",
        "",
        "Current proof:",
        "```lean",
        block.proof_text,
        "```",
        "",
        "An alternative worth knowing:",
    ]
    n_lines = block.proof_text.count("\n") + 1
    lines += [_sketch(c, n_lines) for c in block.candidates]
    lines += ["", "The current proof is correct; this is an offer, not a verdict.", ""]
    return "\n".join(lines)


def render_file(filename: str, blocks: list[BlockReport]) -> str:
    if not blocks:
        return f"## {filename}\n\nNo extraction candidates found.\n"
    out = [f"## {filename}", ""]
    for b in blocks:
        out.append(render_block(b))
    return "\n".join(out)


def render_report(files: dict[str, list[BlockReport]], title: str = "Elegance report") -> str:
    out = [
        f"# {title}",
        "",
        (
            "Generated by the alt-proof sweep. Each section offers "
            "alternatives for proofs that admit them."
        ),
        "",
    ]
    for fn in sorted(files, key=lambda f: -sum(len(b.candidates) for b in files[f])):
        out.append(render_file(fn, files[fn]))
        out.append("")
    return "\n".join(out)
